#!/usr/bin/env node
import fs from 'fs'
import path from 'path'

const cwd = process.cwd()
const dataDir = path.join(cwd, 'public', 'data')
const outFile = path.join(cwd, 'src', 'generated-products.ts')

function titleCase(slug) {
  return slug
    .replace(/[-_]+/g, ' ')
    .replace(/\b\w/g, (c) => c.toUpperCase())
}

if (!fs.existsSync(dataDir)) {
  console.warn('public/data directory not found:', dataDir)
  const content = `/* Generated file - no products found */\nexport type Product = { name: string; slug: string; image: string; descriptionPath?: string };\nconst products: Product[] = [];\nexport default products;\n`;
  fs.writeFileSync(outFile, content, 'utf8')
  console.log('Wrote', outFile)
  process.exit(0)
}

const entries = fs.readdirSync(dataDir, { withFileTypes: true })
const products = []

for (const e of entries) {
  if (!e.isDirectory()) continue
  if (e.name === 'assets') continue
  const dirName = e.name
  const dirPath = path.join(dataDir, dirName)
  let files = []
  try {
    files = fs.readdirSync(dirPath)
  } catch (err) {
    continue
  }

  // find description file (prefer exact name)
  let descFile = files.find(f => f.toLowerCase() === 'description.html') || files.find(f => f.toLowerCase().endsWith('.html'))
  // find image file (prefer image.* name)
  const imageCandidates = files.filter(f => /\.(png|jpe?g|svg|webp)$/i.test(f))
  let imageFile = imageCandidates.find(f => /^image\.(png|jpe?g|svg|webp)$/i.test(f)) || imageCandidates[0]
  const imagePath = imageFile ? `data/${dirName}/${imageFile}` : 'data/assets/placeholder.svg'
  const descriptionPath = descFile ? `data/${dirName}/${descFile}` : undefined
  const name = titleCase(dirName)
  products.push({ name, slug: dirName, image: imagePath, descriptionPath })
}

const outContent = `/* This file is generated by scripts/generate-products.mjs — DO NOT EDIT */\nexport type Product = { name: string; slug: string; image: string; descriptionPath?: string };\n\nconst products: Product[] = ${JSON.stringify(products, null, 2)};\n\nexport default products;\n`;

fs.writeFileSync(outFile, outContent, 'utf8')
console.log('Generated', outFile, 'with', products.length, 'products')
